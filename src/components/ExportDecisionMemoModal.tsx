import React, { useState } from 'react';
import { X, Copy, Check, Printer, FileText } from 'lucide-react';

interface ExportDecisionMemoModalProps {
  decision: any;
  isOpen: boolean;
  onClose: () => void;
}

export const ExportDecisionMemoModal: React.FC<ExportDecisionMemoModalProps> = ({
  decision,
  isOpen,
  onClose
}) => {
  const [copied, setCopied] = useState<boolean>(false);

  if (!isOpen || !decision) return null;

  const report = decision.ai_report || {};

  const generateMarkdownMemo = () => {
    return `# EXECUTIVE STRATEGIC DECISION MEMO
**Document ID:** ${decision.id}
**Date Generated:** ${new Date(decision.created_at || Date.now()).toLocaleDateString()}
**Status:** BINDING STRATEGIC RECORD
**Domain:** ${decision.domain} | **Urgency:** ${decision.urgency} | **Risk Appetite:** ${decision.risk_appetite}
**Key Stakeholders:** ${decision.stakeholders || 'Executive Leadership'}

---

## 1. EXECUTIVE SUMMARY & VERDICT
**Recommended Primary Option:** ${report.recommendedOptionName || decision.recommended_option_name}
**Runner-Up Alternative:** ${report.runnerUpOptionName || 'N/A'}
**Analytical Confidence Score:** ${decision.confidence_score ?? report.confidenceScore ?? 85}%

### Strategic Rationale:
${report.executiveSummary || decision.problem_statement}

**Confidence & Uncertainty Factors:**
${report.confidenceRationale || 'Evaluated across hard constraints, MCDA weighted scoring, and scenario stress-testing.'}

---

## 2. PROBLEM STATEMENT & CONTEXT
${decision.problem_statement}

### Hard Ceilings & Non-Negotiables:
- **Budget Ceiling:** ${decision.budget_constraint || 'N/A'}
- **Timeline Deadline:** ${decision.timeline_constraint || 'N/A'}
- **Non-Negotiables:**
${(decision.non_negotiables || []).map((n: string) => `  - ${n}`).join('\n')}

---

## 3. MULTI-CRITERIA DECISION ANALYSIS (MCDA) RESULTS

${(report.optionEvaluations || []).map((opt: any) => `
### Rank #${opt.rank}: ${opt.optionName}
- **Overall Weighted Score:** ${opt.overallWeightedScore} / 100
- **Constraint Compliance:** ${opt.constraintCompliance}
- **Key Strengths:** ${(opt.strengths || []).join(', ')}
- **Key Weaknesses:** ${(opt.weaknesses || []).join(', ')}
- **Trade-Off Summary:** ${opt.tradeOffSummary}
`).join('\n')}

---

## 4. DISCOVERED DECISION DYNAMICS & SECOND-ORDER EFFECTS
${(report.decisionPatterns || []).map((p: any) => `
- **${p.patternTitle}:** ${p.insight}
  *Strategic Implication:* ${p.strategicImplication}
`).join('\n')}

---

## 5. PROBABILISTIC RISK REGISTER (TOP EXPOSURES)
| Risk ID | Risk Title | Option | Likelihood | Impact | Mitigation Protocol |
| :--- | :--- | :--- | :---: | :---: | :--- |
${(report.riskMatrix || []).map((r: any) => `| ${r.riskId} | ${r.riskTitle} | ${r.affectedOption} | ${r.likelihood}/5 | ${r.impact}/5 | ${r.mitigationStrategy} |`).join('\n')}

---

## 6. EXPLAINABLE AI (XAI) AUDIT & REVERSAL TRIGGERS
- **Decisive Why Winner Won:** ${report.explainabilityAudit?.whyWinnerWon || 'N/A'}
- **Runner-Up Shortfall:** ${report.explainabilityAudit?.whyRunnerUpLost || 'N/A'}

### Reversal Triggers (Flip Conditions):
${(report.explainabilityAudit?.reversalTriggers || []).map((t: string) => `- ${t}`).join('\n')}

---

## 7. 30-60-90 DAY EXECUTION ROADMAP
${(report.executionRoadmap || []).map((ph: any) => `
### ${ph.phase}
- **Objective:** ${ph.objective}
- **Deliverables:**
${(ph.actionItems || []).map((a: string) => `  - ${a}`).join('\n')}
- **Success Metric:** ${ph.successMetric}
`).join('\n')}

---
*Generated by Stratagem AI — Enterprise Decision Intelligence Engine*
`;
  };

  const memoText = generateMarkdownMemo();

  const handleCopy = () => {
    navigator.clipboard.writeText(memoText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    const printWindow = window.open('', '_blank');
    if (printWindow) {
      printWindow.document.write(`
        <html>
          <head>
            <title>Executive Decision Memo - ${decision.title}</title>
            <style>
              body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; padding: 40px; color: #1e293b; line-height: 1.6; }
              h1 { font-size: 24px; border-bottom: 2px solid #e2e8f0; padding-bottom: 12px; }
              h2 { font-size: 18px; margin-top: 24px; color: #0f172a; border-bottom: 1px solid #e2e8f0; padding-bottom: 6px; }
              h3 { font-size: 15px; margin-top: 16px; color: #334155; }
              table { width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 13px; }
              th, td { border: 1px solid #cbd5e1; padding: 8px 12px; text-align: left; }
              th { background-color: #f1f5f9; font-weight: bold; }
              ul { padding-left: 20px; }
              .meta { font-size: 13px; color: #64748b; margin-bottom: 20px; }
            </style>
          </head>
          <body>
            <pre style="white-space: pre-wrap; font-family: inherit;">${memoText}</pre>
            <script>window.onload = function() { window.print(); };</script>
          </body>
        </html>
      `);
      printWindow.document.close();
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="relative w-full max-w-4xl max-h-[90vh] bg-slate-900 border border-slate-800 rounded-2xl shadow-2xl flex flex-col overflow-hidden">
        {/* Header */}
        <div className="p-5 border-b border-slate-800 flex items-center justify-between bg-slate-950/60">
          <div className="flex items-center gap-2.5">
            <div className="p-2 rounded-xl bg-indigo-600/20 text-indigo-400 border border-indigo-500/30">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">Executive Decision Memo Export</h3>
              <p className="text-xs text-slate-400">
                Boardroom-ready, auditable strategic memo formatted for leadership alignment.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-3.5 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold flex items-center gap-1.5 transition-colors"
            >
              {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Markdown'}</span>
            </button>

            <button
              onClick={handlePrint}
              className="px-3.5 py-1.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold flex items-center gap-1.5 transition-colors"
            >
              <Printer className="w-4 h-4" />
              <span>Print / PDF</span>
            </button>

            <button
              onClick={onClose}
              className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors ml-2"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Markdown Content Viewer */}
        <div className="flex-1 overflow-y-auto p-6 bg-slate-950">
          <pre className="text-xs text-slate-300 font-mono whitespace-pre-wrap leading-relaxed select-all">
            {memoText}
          </pre>
        </div>

        {/* Footer */}
        <div className="p-4 border-t border-slate-800 bg-slate-900/60 flex items-center justify-between text-xs text-slate-400">
          <span>Ready for inclusion in executive packets and governance repositories.</span>
          <button
            onClick={onClose}
            className="px-4 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 font-medium"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};

export default ExportDecisionMemoModal;
